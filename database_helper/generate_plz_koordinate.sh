#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Generates the Flyway migration with the German PLZ coordinates (plz_koordinate)
# and the distance function plz_entfernung_km, used by the KO-Kriterium "Entfernung".
# ---------------------------------------------------------------------------
# Data source: GeoNames postal codes, Germany (https://download.geonames.org/export/zip/DE.zip)
#              licensed under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/),
#              attribution: GeoNames (https://www.geonames.org/).
# A PLZ can belong to several places; their coordinates are averaged per PLZ.
#
# Usage (from the project root, Git Bash or Linux):
#   bash database_helper/generate_plz_koordinate.sh [output.sql]
# Default output: backend/src/main/resources/db/migration/V37__add_plz_koordinate.sql
#
# To refresh the data later, write a NEW migration version (an applied Flyway migration must
# not change), e.g.:
#   bash database_helper/generate_plz_koordinate.sh backend/src/main/resources/db/migration/V50__refresh_plz_koordinate.sql
# and replace "CREATE TABLE" by "TRUNCATE plz_koordinate;" in that file.
# ---------------------------------------------------------------------------
set -euo pipefail

OUT="${1:-backend/src/main/resources/db/migration/V37__add_plz_koordinate.sql}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

curl -fsSL -o "$TMP/DE.zip" https://download.geonames.org/export/zip/DE.zip
unzip -q -o "$TMP/DE.zip" DE.txt -d "$TMP"

{
  cat <<'SQL'
-- ---------------------------------------------------------------------------
-- German PLZ coordinates for the KO-Kriterium "Entfernung" (Luftlinie).
-- Generated by database_helper/generate_plz_koordinate.sh – do not edit by hand.
-- Data: GeoNames (https://www.geonames.org/), postal codes DE, licensed under
-- CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Coordinates of all
-- places of one PLZ are averaged.
-- ---------------------------------------------------------------------------
CREATE TABLE plz_koordinate (
    plz VARCHAR(5) PRIMARY KEY,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL
);

-- Straight-line distance in km between two PLZ (haversine, earth radius 6371 km).
-- PLZ are padded to 5 digits (Kandidat stores them as numbers: 1067 -> 01067).
-- NULL if a PLZ is missing or unknown.
CREATE OR REPLACE FUNCTION plz_entfernung_km(plz_a TEXT, plz_b TEXT) RETURNS DOUBLE PRECISION
    LANGUAGE sql STABLE AS $$
    SELECT 2 * 6371 * asin(sqrt(
               power(sin(radians(b.lat - a.lat) / 2), 2)
               + cos(radians(a.lat)) * cos(radians(b.lat)) * power(sin(radians(b.lon - a.lon) / 2), 2)))
    FROM plz_koordinate a, plz_koordinate b
    WHERE a.plz = lpad(trim(plz_a), 5, '0')
      AND b.plz = lpad(trim(plz_b), 5, '0')
$$;

SQL
  # DE.txt columns (tab-separated): 2 = PLZ, 10 = latitude, 11 = longitude.
  # First pass: sorted unique PLZ (stable output order); second pass: averaged coordinates.
  awk -F '\t' '$2 ~ /^[0-9]{5}$/ && $10 != "" && $11 != "" { print $2 }' "$TMP/DE.txt" \
    | sort -u > "$TMP/plz_sorted.txt"
  awk -F '\t' '
    NR == FNR { order[++count] = $1; next }
    $2 ~ /^[0-9]{5}$/ && $10 != "" && $11 != "" { lat[$2] += $10; lon[$2] += $11; n[$2]++ }
    END {
      print "INSERT INTO plz_koordinate (plz, lat, lon) VALUES"
      for (i = 1; i <= count; i++) {
        p = order[i]
        printf "    (\x27%s\x27, %.5f, %.5f)%s\n", p, lat[p] / n[p], lon[p] / n[p], (i < count ? "," : ";")
      }
    }' "$TMP/plz_sorted.txt" "$TMP/DE.txt"
} > "$OUT"

echo "Written $OUT ($(grep -c "^    ('" "$OUT") PLZ)"
